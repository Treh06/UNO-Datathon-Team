"""Convert the simulator's authorization JSONL without exposing ground truth.

The supported source is its documented USD, MCC 7922 ticket-request layout.
No card, BIN, linkage token, release time, or event allocation is invented.
Actor/tactic metadata stays in a separately requested ground-truth dataframe.
"""

from __future__ import annotations

import json
import math
import re
from datetime import date, datetime, timezone
from decimal import Decimal, InvalidOperation
from numbers import Real
from pathlib import Path
from typing import Iterator

import pandas as pd

from .data import LABEL, validate_events

_TRUTH_FIELDS = frozenset((LABEL, "actor_id", "tactic"))
_SOURCE_TOKENS = {
    "txn_id": "order_id",
    "card_token": "card_id",
    "bin": "card_bin",
    "merchant_id": "merchant_id",
}
_OPTIONAL_TOKENS = {
    "ship_addr_hash": "shipping_hash",
    "bill_addr_hash": "billing_hash",
    "email_hash": "email_hash",
    "device_id": "device_id",
    "event_id": "event_id",
    "card_type": "card_type",
}


def _token(payload: dict, key: str, *, optional: bool = False) -> str:
    value = payload.get(key)
    if optional and (value is None or value == ""):
        return ""
    if not isinstance(value, str) or not value.strip():
        raise ValueError(
            f"{key} must be a nonempty string; identifiers are never generated by the adapter."
        )
    return value.strip()


def _unique_object(pairs: list[tuple[str, object]]) -> dict:
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate JSON field {key!r}.")
        result[key] = value
    return result


def _invalid_constant(value: str) -> None:
    raise ValueError(f"Nonfinite JSON value {value!r} is not permitted.")


def _records_frame(rows: list[dict]) -> pd.DataFrame:
    """Build object-typed columns so pandas does not infer dates row by row."""
    columns = dict.fromkeys(column for row in rows for column in row)
    return pd.DataFrame(
        {column: pd.Series([row.get(column) for row in rows], dtype=object) for column in columns}
    )


def _read_objects(path: str | Path) -> Iterator[tuple[int, dict]]:
    location = Path(path)
    with location.open(encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, 1):
            if not line.strip():
                continue
            try:
                payload = json.loads(
                    line, object_pairs_hook=_unique_object, parse_constant=_invalid_constant
                )
            except ValueError as exc:
                raise ValueError(f"{location}:{line_number}: invalid JSON: {exc}") from exc
            if not isinstance(payload, dict):
                raise ValueError(f"{location}:{line_number}: each JSONL record must be an object.")
            yield line_number, payload


def _authorization_fields(payload: dict) -> dict:
    """Map the source allowlist before a single-row or batch validation."""
    if not isinstance(payload, dict):
        raise ValueError("An authorization request must be a JSON object.")
    forbidden = _TRUTH_FIELDS.intersection(payload)
    if forbidden:
        raise ValueError(
            f"Ground-truth fields are forbidden in authorization requests: {', '.join(sorted(forbidden))}."
        )
    if "product_category" in payload:
        category = payload["product_category"]
        if not isinstance(category, str) or category.strip().lower() != "tickets":
            raise ValueError("Only product_category='tickets' authorizations are supported.")
    currency = payload.get("currency")
    if not isinstance(currency, str) or currency.strip().upper() != "USD":
        raise ValueError(
            "Only explicit USD authorizations are supported; no currency conversion is performed."
        )
    if _token(payload, "mcc") != "7922":
        raise ValueError("Only simulator ticket authorizations with mcc='7922' are supported.")
    timestamp_value = _token(payload, "event_ts")
    try:
        parsed = datetime.fromisoformat(timestamp_value.replace("Z", "+00:00"))
        if parsed.tzinfo is None or parsed.utcoffset() is None:
            raise ValueError("missing timezone")
        timestamp = parsed.astimezone(timezone.utc)
    except (TypeError, ValueError, OverflowError) as exc:
        raise ValueError("event_ts must be a valid timezone-aware ISO-8601 timestamp.") from exc

    order = {target: _token(payload, source) for source, target in _SOURCE_TOKENS.items()}
    fraction = re.search(r"[Tt ]\d{2}:\d{2}:\d{2}[.,](\d+)", timestamp_value)
    normalized_timestamp = timestamp.isoformat(timespec="seconds").replace("+00:00", "Z")
    if fraction and fraction.group(1).rstrip("0"):
        normalized_timestamp = normalized_timestamp[:-1] + "." + fraction.group(1).rstrip("0") + "Z"
    order.update(timestamp=normalized_timestamp, category="tickets")
    for source, target in _OPTIONAL_TOKENS.items():
        if source in payload and payload[source] is not None:
            order[target] = _token(payload, source, optional=True)
    for key in ("amount", "quantity"):
        if key == "quantity" and payload.get(key) is None:
            continue
        value = payload.get(key)
        # The HTTP schema and its original sample represent Decimal payments
        # as JSON strings. Keep USD units and reject nonfinite/overflow values.
        if key == "amount" and isinstance(value, (str, Decimal)):
            try:
                decimal_amount = Decimal(value)
                if not decimal_amount.is_finite():
                    raise ValueError("amount must be a finite payment.")
                value = float(decimal_amount)
            except (InvalidOperation, OverflowError) as exc:
                raise ValueError(
                    "amount must be a finite payment number or decimal string."
                ) from exc
        if isinstance(value, bool) or not isinstance(value, Real) or not math.isfinite(value):
            raise ValueError(f"{key} must be a finite JSON number.")
        if value <= 0 or (key == "quantity" and value % 1 != 0):
            raise ValueError(
                f"{key} must be positive" + (" whole ticket units." if key == "quantity" else ".")
            )
        order[key] = value

    issue_value = payload.get("card_issue_date")
    if issue_value is not None and issue_value != "":
        if not isinstance(issue_value, str) or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", issue_value):
            raise ValueError("card_issue_date must be an ISO date in YYYY-MM-DD format.")
        try:
            issued = datetime.combine(
                date.fromisoformat(issue_value), datetime.min.time(), tzinfo=timezone.utc
            )
        except (ValueError, TypeError, OverflowError) as exc:
            raise ValueError("card_issue_date must be a valid ISO date.") from exc
        if issued > timestamp:
            raise ValueError("card_issue_date cannot be after event_ts in UTC.")
        try:
            order["card_age_days"] = (timestamp - issued).total_seconds() / 86400
        except (ValueError, OverflowError) as exc:
            raise ValueError(
                "card_issue_date is outside the supported elapsed-time range."
            ) from exc

    # The generator's quantity_cap is a sampling setting, not a supplied
    # per-buyer event allocation. Its drops are not observed release metadata.
    return order


def authorization_to_order(payload: dict) -> dict:
    """Convert one label-free authorization to the validated detector schema.

    ``event_ts`` must include a timezone and is converted to UTC. An available
    ISO ``card_issue_date`` is interpreted as midnight UTC when computing
    elapsed card-age days. Unknown source fields are ignored, not features.
    """
    return validate_events(_records_frame([_authorization_fields(payload)])).iloc[0].to_dict()


def read_ground_truth(path: str | Path) -> pd.DataFrame:
    """Read offline labels and diagnostics separately from model input fields."""
    rows = []
    seen = set()
    for line_number, payload in _read_objects(path):
        try:
            txn_id = _token(payload, "txn_id")
            if txn_id in seen:
                raise ValueError(f"Duplicate ground-truth txn_id {txn_id!r}.")
            label = payload.get(LABEL)
            if isinstance(label, bool) or not isinstance(label, int) or label not in (0, 1):
                raise ValueError("is_scalper must be an integer 0 or 1 in ground truth.")
            row = {
                "txn_id": txn_id,
                LABEL: label,
                "actor_id": _token(payload, "actor_id"),
                "tactic": _token(payload, "tactic"),
            }
        except ValueError as exc:
            raise ValueError(f"{path}:{line_number}: {exc}") from exc
        seen.add(txn_id)
        rows.append(row)
    if not rows:
        raise ValueError(f"Ground-truth file is empty: {path}")
    return pd.DataFrame(rows, columns=("txn_id", LABEL, "actor_id", "tactic"))


def read_authorizations(
    requests_path: str | Path, *, ground_truth_path: str | Path | None = None
) -> pd.DataFrame:
    """Read stable chronological orders, joining labels only when requested.

    Explicit ground truth must match every request exactly once, with neither
    missing nor extra transaction IDs. Only ``is_scalper`` enters the canonical
    frame; ``actor_id`` and ``tactic`` remain offline diagnostic metadata.
    """
    rows = []
    seen = set()
    for line_number, payload in _read_objects(requests_path):
        try:
            row = _authorization_fields(payload)
            txn_id = row["order_id"]
            if txn_id in seen:
                raise ValueError(f"Duplicate request txn_id {txn_id!r}.")
        except ValueError as exc:
            raise ValueError(f"{requests_path}:{line_number}: {exc}") from exc
        seen.add(txn_id)
        rows.append(row)
    if not rows:
        raise ValueError(f"Authorization request file is empty: {requests_path}")
    result = validate_events(_records_frame(rows))
    if ground_truth_path is not None:
        truth = read_ground_truth(ground_truth_path)
        truth_ids = set(truth.txn_id)
        missing, extra = seen - truth_ids, truth_ids - seen
        if missing or extra:
            raise ValueError(
                "Ground truth must match requests exactly: "
                f"{len(missing)} missing label(s), {len(extra)} extra txn_id(s)."
            )
        labels = truth.set_index("txn_id")[LABEL]
        result[LABEL] = result.order_id.map(labels).astype(int)
        result = validate_events(result, require_labels=True)
    return result
